// Deploys EvidenceRegistry to the local Hardhat node and registers the demo
// consortium. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const Role = { Investigator: 1, Analyst: 2, Court: 3 };

async function main() {
  const signers = await hre.ethers.getSigners();
  const [authority] = signers;

  const registry = await hre.ethers.deployContract("EvidenceRegistry", [], authority);
  await registry.waitForDeployment();
  const address = await registry.getAddress();
  console.log(`EvidenceRegistry deployed to ${address} by the State Forensic Authority ${authority.address}`);

  // Same demo consortium as the web app (frontend/js/app.js). All names are fictional.
  const consortium = [
    [signers[1], Role.Investigator, "Cyber Crime Cell - North"],
    [signers[2], Role.Investigator, "City Police Station 7"],
    [signers[3], Role.Analyst, "Regional Forensic Science Lab"],
    [signers[4], Role.Court, "District Court Registry (demo)"],
  ];
  for (const [signer, role, name] of consortium) {
    await (await registry.registerMember(signer.address, role, name)).wait();
    console.log(`  registered ${name.padEnd(32)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
